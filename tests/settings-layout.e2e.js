import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { startTestServer } from './helpers/runtime.js';

test('设置分区、分页音色库、草稿及独立保存关联在真实浏览器中一致', { timeout: 120000 }, async t => {
  const app = await startTestServer(t, { settings: { qq: { enabled: false }, proactive: { enabled: false } } });
  const executablePath = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(fs.existsSync);
  const browser = await chromium.launch({ executablePath, headless: true });
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const headers = { origin: app.base, 'x-bizhi-request': '1' };
  const current = async () => (await context.request.get(app.base + '/api/settings')).json();
  await page.route('**/api/qq/setup', async route => {
    const response = await route.fetch(); const data = await response.json();
    await route.fulfill({ json: { ...data, provider: { ...data.provider, id: 'snowluma', name: 'SnowLuma', qrMode: 'desktop', webUiUrl: 'http://127.0.0.1:5099/', processesUrl: 'http://127.0.0.1:5099/processes' }, background: { installed: true, enabled: true, logon: true, unlock: true, resume: true, periodicMinutes: 5, fresh: true } } });
  });
  await context.route('http://127.0.0.1:5099/**', route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: '<h1>模拟 SnowLuma 控制台</h1>' }));
  const models = Array.from({ length: 36 }, (_, i) => ({ id: `fixture-${i}`, title: `测试音色 ${i}`, family: i % 2 ? '男声' : '女声', available: true, bytes: 55000000 }));
  await page.route('**/api/voice/setup', async route => {
    const snapshot = await current();
    await route.fulfill({ json: { voices: [{ id: 'zh-CN-XiaoxiaoNeural', label: '基础音色' }, { id: 'local-matcha', label: '本地音色' }], rvc: { installed: true, baseWeights: true, modelCount: 36, readyCount: 36, models, ...snapshot.settings.tts.rvc } } });
  });
  // UI success fixture uses the actual settings store/revision; no model is loaded.
  await page.route('**/api/voice/rvc/select', async route => {
    const before = await current();
    const response = await context.request.put(app.base + '/api/settings', { headers: { ...headers, 'If-Match': route.request().headers()['if-match'] }, data: { tts: { rvc: { ...before.settings.tts.rvc, ...route.request().postDataJSON() } } } });
    const saved = await response.json();
    await route.fulfill({ status: response.status(), json: response.ok() ? { ...saved, ok: true, rvc: saved.settings.tts.rvc, selected: { title: '测试音色' } } : saved });
  });
  await page.goto(app.base + '/?view=settings');
  await page.waitForFunction(() => document.querySelector('#setName').value.length > 0);
  await page.locator('#qqConsoleLink').waitFor({ state: 'visible' });
  const popupReady = context.waitForEvent('page');
  await page.locator('#qqConsoleLink').click();
  const popup = await popupReady; await popup.getByRole('heading', { name: '模拟 SnowLuma 控制台' }).waitFor();
  assert.equal(popup.url(), 'http://127.0.0.1:5099/');
  assert.equal(await popup.evaluate(() => window.opener === null), true);
  await popup.close();
  assert.match(await page.locator('#qqConsoleProcesses').getAttribute('href'), /\/processes$/);
  assert.equal(await page.locator('#qqConsoleOverview').getAttribute('target'), '_blank');
  await page.locator('#setName').fill('分区切换保留草稿');
  await page.getByRole('tab', { name: '聊天与记忆', exact: true }).click();
  await page.locator('#setSearchDailyMax').fill('13');
  await page.locator('#set-card-memory summary').click();
  await page.locator('#setDreamHour').fill('0');
  await page.getByRole('tab', { name: '主动陪伴', exact: true }).click();
  await page.locator('#setIdleMin').fill('37');
  await page.getByRole('tab', { name: '聊天与记忆', exact: true }).click();
  await page.locator('#saveSectionBtn').click();
  await page.waitForFunction(() => !document.querySelector('#saveSectionBtn').disabled);
  assert.equal((await current()).settings.search.dailyMax, 13);
  assert.notEqual((await current()).settings.proactive.idleMinutesMin, 37);
  assert.notEqual((await current()).settings.companion.name, '分区切换保留草稿');
  await page.getByRole('tab', { name: '界面与系统', exact: true }).click();
  const sentinelRequests = [];
  await page.route('**/api/sentinel/run', async route => { sentinelRequests.push(route.request().postDataJSON()); await route.fulfill({ json: { ok: true, bytes: 1024 } }); });
  await page.locator('#sentinelBeatBtn').click();
  await page.locator('#sentinelBackupBtn').click();
  assert.deepEqual(sentinelRequests, [{ what: 'heartbeat' }, { what: 'backup' }], '报平安和备份不能重复编码或混为同一操作');
  await page.getByRole('tab', { name: '语音与感官', exact: true }).click();
  assert.equal(await page.locator('#rvcModelList .compare-row').count(), 6);
  assert.equal(await page.locator('#rvcModelList').isVisible(), false, '目录不应铺在主页面');
  await page.locator('#rvcLibraryBtn').click();
  await page.locator('#rvcLibraryNext').click();
  assert.match(await page.locator('#rvcLibraryPage').innerText(), /2 \/ 6/);
  await page.locator('#rvcLibrarySearch').fill('测试音色 35');
  assert.equal(await page.locator('#rvcModelList .compare-row').count(), 1);
  assert.equal(await page.locator('#rvcLibraryPrev').isDisabled(), true);
  await page.getByRole('button', { name: '用这个声音', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#rvcEnabled').checked);
  assert.equal((await current()).settings.tts.rvc.model, 'fixture-35');
  let releasePreview, previewRequested;
  const heldPreview = new Promise(resolve => releasePreview = resolve);
  const previewStarted = new Promise(resolve => previewRequested = resolve);
  await page.route('**/api/voice/rvc/preview', async route => { previewRequested(); await heldPreview; await route.fulfill({ json: { ok: true, url: '/unused-preview.wav', title: '迟到试听', ms: 1 } }); });
  await page.getByRole('button', { name: '试听这个', exact: true }).click();
  await previewStarted;
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#rvcLibraryDialog').isVisible(), false);
  const previewDone = page.waitForResponse(r => r.url().endsWith('/api/voice/rvc/preview'));
  releasePreview(); await previewDone;
  assert.equal(await page.locator('#rvcPreviewPlayer').getAttribute('src'), null, '关闭弹窗后的迟到结果不能突然播放');
  await page.locator('#setVoiceMax').fill('3');
  const saved = page.waitForResponse(r => r.url().endsWith('/api/settings') && r.request().method() === 'PUT');
  await page.locator('#saveSectionBtn').click();
  assert.equal((await saved).status(), 200, 'RVC 立即保存后必须更新版本，语音保存不能冲突');
  assert.equal((await current()).settings.tts.rvc.model, 'fixture-35');
  await page.route('**/api/voice/compare', route => route.fulfill({ json: { results: [{ ok: true, voice: 'local-matcha', label: '本地音色', engine: 'fixture', ms: 1, bytes: 1, url: '/unused-compare.wav' }] } }));
  await page.locator('#voiceCompareBtn').click();
  await page.getByRole('button', { name: '就用这个', exact: true }).click();
  assert.equal(await page.locator('#voiceCompareDialog').isVisible(), false);
  assert.match(await page.locator('#saveHint').innerText(), /未保存/);
  assert.equal(await page.locator('#setVoiceName').inputValue(), 'local-matcha');
  await page.getByRole('tab', { name: 'X / 推特', exact: true }).click();
  await page.locator('#setXDailyLike').fill('17');
  await page.getByRole('tab', { name: '小红书', exact: true }).click();
  await page.locator('#set-card-xhs details > summary').click();
  await page.locator('#setXhsLikeMax').fill('4');
  await page.locator('#saveSectionBtn').click();
  await page.waitForFunction(() => !document.querySelector('#saveSectionBtn').disabled);
  assert.equal((await current()).settings.social.xhsDailyLikeMax, 4);
  assert.notEqual((await current()).settings.social.xDailyLikeMax, 17);
  await page.getByRole('tab', { name: 'X / 推特', exact: true }).click();
  assert.equal(await page.locator('#setXDailyLike').inputValue(), '17');
  await page.getByRole('tab', { name: '角色与称呼', exact: true }).click();
  assert.equal(await page.locator('#setName').inputValue(), '分区切换保留草稿');
  const autoSpeak = (await current()).settings.ui.autoSpeak;
  await page.locator('.rail-btn[data-view="chat"]').click();
  await page.locator('#voiceBtn').click();
  await page.locator('.rail-btn[data-view="settings"]').click();
  await page.getByRole('tab', { name: '界面与系统', exact: true }).click();
  assert.equal(await page.locator('#setAutoSpeak').isChecked(), !autoSpeak);
  await page.locator('#saveSectionBtn').click();
  await page.waitForFunction(() => !document.querySelector('#saveSectionBtn').disabled);
  assert.equal((await current()).settings.ui.autoSpeak, !autoSpeak);
  assert.notEqual((await current()).settings.companion.name, '分区切换保留草稿');
  await page.waitForFunction(() => document.querySelector('#toast').className === 'toast');
  const shots = path.resolve('data/browser-verification'); fs.mkdirSync(shots, { recursive: true });
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    for (const section of ['identity', 'chat', 'proactive', 'voice', 'qq', 'social', 'xhs', 'x', 'system']) {
      await page.locator(`[data-settings-tab="${section}"]`).click();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${width}/${section} overflow`);
      const gaps = await page.locator('#settingsCards > .card:not([hidden])').evaluateAll(cards => cards.slice(1).map((card, i) => Math.round(card.getBoundingClientRect().top - cards[i].getBoundingClientRect().bottom)));
      assert.ok(gaps.every(gap => gap >= 12 && gap <= 20), `${width}/${section} cards have gaps: ${gaps}`);
    }
    await page.locator('[data-settings-tab="voice"]').click();
    await page.screenshot({ path: path.join(shots, `settings-sections-${width}.png`) });
    await page.locator('#rvcLibraryBtn').click();
    await page.locator('#rvcLibrarySearch').fill('');
    await page.screenshot({ path: path.join(shots, `settings-library-${width}.png`) });
    assert.equal(await page.locator('#rvcLibraryDialog').evaluate(node => node.scrollWidth > node.clientWidth + 1), false);
    await page.getByRole('button', { name: '关闭音色库', exact: true }).click();
  }
  assert.deepEqual(errors, []);
});
